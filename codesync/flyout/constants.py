"""Flyout sizes and motion. These match the Remote Islands tray panel."""

from PySide6.QtCore import QEasingCurve
from PySide6.QtGui import QFont

FLYOUT_PANEL_FIXED_WIDTH = 360
FLYOUT_PANEL_FONT_FAMILY_PREFERRED = "Segoe UI Variable"
FLYOUT_PANEL_FONT_FAMILY_FALLBACK = "Segoe UI"
FLYOUT_PANEL_FONT_POINT_SIZE = 10

TRAY_FLYOUT_SLIDE_OPEN_DURATION_MS = 170
TRAY_FLYOUT_SLIDE_CLOSE_DURATION_MS = 150
TRAY_FLYOUT_SLIDE_OFFSET_MIN_PX = 20
TRAY_FLYOUT_SLIDE_OFFSET_SCALE_PX = 80.0
TRAY_FLYOUT_SLIDE_OPEN_EASING = QEasingCurve.Type.OutCubic
TRAY_FLYOUT_SLIDE_CLOSE_EASING = QEasingCurve.Type.InCubic
TRAY_FLYOUT_SLIDE_FADE_IN_MS = 120
TRAY_FLYOUT_SLIDE_FADE_OUT_MS = 120

TRAY_PEEK_SLIDE_OPEN_DURATION_MS = 200
TRAY_PEEK_SLIDE_CLOSE_DURATION_MS = 200
TRAY_PEEK_SLIDE_OFFSET_MIN_PX = 20
TRAY_PEEK_SLIDE_OFFSET_SCALE_PX = 36.0
TRAY_PEEK_SLIDE_OPEN_EASING = QEasingCurve.Type.OutCubic
TRAY_PEEK_SLIDE_CLOSE_EASING = QEasingCurve.Type.InCubic
TRAY_PEEK_SLIDE_FADE_IN_MS = TRAY_PEEK_SLIDE_OPEN_DURATION_MS
TRAY_PEEK_SLIDE_FADE_OUT_MS = TRAY_PEEK_SLIDE_CLOSE_DURATION_MS

APP_DISPLAY_NAME = "CodeSync"


def flyout_panel_font() -> QFont:
    font = QFont(FLYOUT_PANEL_FONT_FAMILY_PREFERRED, FLYOUT_PANEL_FONT_POINT_SIZE)
    if not font.exactMatch():
        font = QFont(FLYOUT_PANEL_FONT_FAMILY_FALLBACK, FLYOUT_PANEL_FONT_POINT_SIZE)
    return font
